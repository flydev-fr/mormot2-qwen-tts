# Compile the shaders of the 12 Hz decoder (tools\tts\vk\*.comp) to SPIR-V and
# write them as Pascal constants into src\tts\mormot.ai.tts.qwen.spv.inc
# (versioned: neither the build nor the run needs a shader compiler).
# The format of spv2pas.py of mormot2-ai.
# - glslang: the official Khronos release
#   (https://github.com/KhronosGroup/glslang/releases); -Glslang, or the
#   GLSLANG environment variable, or glslang.exe on the PATH
param(
  [string]$Glslang = $env:GLSLANG
)
$ErrorActionPreference = 'Stop'
if (-not $Glslang) {
  $cmd = Get-Command glslang -ErrorAction SilentlyContinue
  if ($cmd) { $Glslang = $cmd.Source }
}
if (-not $Glslang -or -not (Test-Path -LiteralPath $Glslang)) {
  throw "glslang not found (-Glslang <path>, GLSLANG or PATH; https://github.com/KhronosGroup/glslang/releases)"
}
$out = Join-Path $PSScriptRoot '..\..\..\src\tts\mormot.ai.tts.qwen.spv.inc'
$tmp = Join-Path ([IO.Path]::GetTempPath()) ('qwen-spv-' + [Guid]::NewGuid())
New-Item -ItemType Directory $tmp | Out-Null
try {
  $lines = [Collections.Generic.List[string]]::new()
  $lines.Add('// generated by tools\tts\vk\build-shaders.ps1 from tools\tts\vk\*.comp - do not edit')
  $lines.Add('')
  $lines.Add('const')
  foreach ($f in Get-ChildItem -LiteralPath $PSScriptRoot -Filter *.comp | Sort-Object Name) {
    $spv = Join-Path $tmp ($f.BaseName + '.spv')
    # SPIR-V for Vulkan 1.0: any driver takes it; -Os: short constants
    $log = & $Glslang -V --target-env vulkan1.0 -Os -o $spv $f.FullName 2>&1
    if ($LASTEXITCODE -ne 0) { throw "$($f.Name): $($log -join "`n")" }
    $bytes = [IO.File]::ReadAllBytes($spv)
    if (($bytes.Length % 4) -ne 0 -or [BitConverter]::ToUInt32($bytes, 0) -ne 0x07230203) {
      throw "$($f.Name): not a little-endian SPIR-V module"
    }
    $n = $bytes.Length / 4
    $lines.Add(('  SPV_QWEN_{0}: array[0..{1}] of cardinal = (' -f $f.BaseName.ToUpper(), ($n - 1)))
    for ($i = 0; $i -lt $n; $i += 8) {
      $words = for ($j = $i; $j -lt [Math]::Min($i + 8, $n); $j++) {
        '${0:x8}' -f [BitConverter]::ToUInt32($bytes, $j * 4)
      }
      $end = if ($i + 8 -ge $n) { ');' } else { ',' }
      $lines.Add('    ' + ($words -join ', ') + $end)
    }
    $lines.Add('')
  }
  [IO.File]::WriteAllText([IO.Path]::GetFullPath($out), ($lines -join "`r`n") + "`r`n")
  "written: $([IO.Path]::GetFullPath($out))"
}
finally {
  Remove-Item -LiteralPath $tmp -Recurse -Force
}
